#!/usr/bin/env bash
# zsh.sh — Liberator: shell + prompt
# Frees you from the default shell.

# Detect current default shell (pipefail-safe)
_zsh_current_shell() {
  # macOS: dscl
  if command -v dscl &>/dev/null; then
    local dscl_out
    dscl_out="$(dscl . -read /Users/"$(whoami)" UserShell 2>/dev/null || true)"
    if [[ -n "$dscl_out" ]]; then
      echo "$dscl_out" | awk '{print $2}'
      return 0
    fi
  fi
  # Linux: getent
  if command -v getent &>/dev/null; then
    local getent_out
    getent_out="$(getent passwd "$(whoami)" 2>/dev/null || true)"
    if [[ -n "$getent_out" ]]; then
      echo "$getent_out" | cut -d: -f7
      return 0
    fi
  fi
  # Fallback
  echo "$SHELL"
}

# Where install writes the iTerm2 ssh wrapper, and so the file zsh_check reads.
_zsh_iterm2_ssh_colors_file() {
  echo "$HOME/.config/molt/iterm2-ssh-colors.sh"
}

# The house's local domains, one per line in file order, from the user repo's
# config/network/local-domains (one domain per line; blank lines and # comments
# ignored). Prints nothing when there is no such file, so the wrapper matches
# bare host names only. Fails when the file is there but cannot be read.
_zsh_local_domains() {
  local user_repo file
  user_repo="$(molt_find_user_repo 2>/dev/null)" || return 0
  file="$user_repo/config/network/local-domains"
  [[ -e "$file" ]] || return 0
  if ! awk '{ sub(/#.*/, ""); gsub(/[[:space:]]/, ""); if (length) print }' "$file"; then
    molt_error "zsh: $(molt_tilde "$file") could not be read"
    return 1
  fi
}

# Prints the iTerm2 SSH background colors script, built from instance.toml
# data, or nothing when no instance declares [terminal] ssh_bg_color. The script
# wraps ssh with per-host background color changes, matching each host by its
# bare name and under each of _zsh_local_domains. When ssh returns, the tab goes
# back to this sleeve's own [terminal] bg_color, or to black where the sleeve
# declares none. zsh_check and _zsh_generate_iterm2_ssh_colors both use it, so
# the check compares the file with exactly what install would write.
_zsh_iterm2_ssh_colors() {
  local entries
  entries="$(molt_instances_field "ssh_bg_color" "terminal" 2>/dev/null)" || entries=""
  [[ -z "$entries" ]] && return 0

  local domains
  domains="$(_zsh_local_domains)" || return 1

  local this_host reset
  this_host="$(molt_hostname)" || this_host=""
  reset="$(molt_instances_field "bg_color" "terminal" 2>/dev/null | awk -F: -v h="$this_host" '$1 == h { print $2 }')"
  [[ -n "$reset" ]] || reset=000000

  # Single quotes are intentional: we're writing a script, not expanding variables
  # shellcheck disable=SC2016,SC2028
  {
    echo '# iTerm2 host-aware SSH background colors'
    echo '# GENERATED by molt resleeve -- do not edit'
    echo '# Source: instances/*/instance.toml [terminal] ssh_bg_color and bg_color,'
    echo '# and config/network/local-domains'
    echo ''
    echo 'if [[ "$TERM_PROGRAM" == "iTerm.app" ]]; then'
    echo '  _iterm2_set_bg() { printf "\033]1337;SetColors=bg=%s\007" "$1"; }'
    echo ''
    echo '  ssh() {'
    echo '    local host rc'
    echo '    for arg in "$@"; do'
    echo '      case "$arg" in'
    echo '        -*) continue ;;'
    echo '        *@*) host="${arg##*@}"; break ;;'
    echo '        *) host="$arg"; break ;;'
    echo '      esac'
    echo '    done'
    echo ''
    echo '    case "$host" in'
    local hostname color domain
    while IFS=: read -r hostname color; do
      [[ -z "$hostname" ]] && continue
      printf '      %s' "$hostname"
      while IFS= read -r domain; do
        if [[ -n "$domain" ]]; then printf '|%s.%s' "$hostname" "$domain"; fi
      done <<< "$domains"
      printf ') _iterm2_set_bg %s ;;\n' "$color"
    done <<< "$entries"
    echo '    esac'
    echo ''
    echo '    command ssh "$@"'
    echo '    rc=$?'
    printf '    _iterm2_set_bg %s  # back to [terminal] bg_color\n' "$reset"
    echo '    return $rc'
    echo '  }'
    echo 'fi'
  }
}

# Writes _zsh_iterm2_ssh_colors to $1, and nothing when it prints nothing.
_zsh_generate_iterm2_ssh_colors() {
  local target="$1" script
  script="$(_zsh_iterm2_ssh_colors)" || return 1
  [[ -z "$script" ]] && return 0

  if ! mkdir -p "$(dirname "$target")"; then
    molt_error "zsh: $(molt_tilde "$(dirname "$target")") could not be made, so the iTerm2 SSH colors were not generated"
    return 1
  fi
  printf '%s\n' "$script" > "$target" || {
    molt_error "zsh: $(molt_tilde "$target") could not be written, so the iTerm2 SSH colors were not generated"
    return 1
  }
  molt_info "Generated iTerm2 SSH colors: $target"
}

# Names why the iTerm2 SSH colors file is not what install would write now, and
# prints nothing when it is. install writes it only when a check fails, so
# without this a [terminal] colour or local-domains change never reached it.
_zsh_iterm2_ssh_colors_fault() {
  local target script
  target="$(_zsh_iterm2_ssh_colors_file)"
  if ! script="$(_zsh_iterm2_ssh_colors)"; then
    echo "cannot be checked: its contents could not be built"
    return 0
  fi
  [[ -n "$script" ]] || return 0
  if [[ ! -e "$target" ]]; then
    echo "is missing"
    return 0
  fi
  # cmp exits 1 when the files differ and 2 when it could not compare them.
  local tmp rc=0
  if ! tmp="$(mktemp "${TMPDIR:-/tmp}/molt-iterm2.XXXXXX")"; then
    echo "cannot be checked: mktemp failed"
    return 0
  fi
  if printf '%s\n' "$script" > "$tmp"; then
    cmp -s "$tmp" "$target" || rc=$?
  else
    rc=2
  fi
  rm -f "$tmp"
  case "$rc" in
    0) ;;
    1) echo "differs from the instances' [terminal] colours or local-domains — re-rendering" ;;
    *) echo "cannot be checked: cmp could not compare it" ;;
  esac
}

zsh_check() {
  local ok=0

  # Is zsh installed?
  if ! command -v zsh &>/dev/null; then
    molt_info "zsh: not installed"
    return 1
  fi

  # Is zsh the default shell?
  local current_shell
  current_shell="$(_zsh_current_shell)"
  if [[ "$current_shell" != *"zsh"* ]]; then
    molt_info "zsh: installed but not default shell (current: $current_shell)"
    ok=1
  fi

  # Is Starship installed?
  if ! command -v starship &>/dev/null; then
    molt_info "zsh: Starship prompt not installed"
    ok=1
  fi

  # Starship is rendered, not linked, so a change to its template or to instance
  # vars does not propagate on its own -- molt only renders when a check reports
  # not-ok. Ask for it.
  if molt_config_stale "config/starship/starship.toml" "$HOME/.config/starship.toml"; then
    molt_info "zsh: ~/.config/starship.toml differs from its template or instance vars — re-rendering"
    ok=1
  fi

  # Are config files linked?
  local user_repo
  user_repo="$(molt_find_user_repo 2>/dev/null || echo "")"
  if [[ -n "$user_repo" ]]; then
    # _install links .zshrc, .zshenv and .zprofile, so each must be checked.
    # Checking only .zshrc let a broken .zshenv or .zprofile report healthy.
    local zf
    for zf in .zshrc .zshenv .zprofile; do
      if ! molt_link_healthy "$HOME/$zf"; then
        molt_info "zsh: ~/${zf} $(molt_link_fault "$HOME/$zf")"
        ok=1
      fi
    done

    local colors_fault
    colors_fault="$(_zsh_iterm2_ssh_colors_fault)"
    if [[ -n "$colors_fault" ]]; then
      molt_info "zsh: $(molt_tilde "$(_zsh_iterm2_ssh_colors_file)") $colors_fault"
      ok=1
    fi
  fi

  # Is starship config present and valid? (catches dangling symlinks after template migration)
  if [[ ! -e "$HOME/.config/starship.toml" ]]; then
    molt_info "zsh: ~/.config/starship.toml missing or dangling"
    ok=1
  fi

  return $ok
}

zsh_install() {
  # Verify zsh is installed
  if ! command -v zsh &>/dev/null; then
    molt_error "zsh not found. Install it (eg apt install zsh, brew install zsh) then re-run."
    return 1
  fi

  # Set as default shell
  local zsh_path
  zsh_path="$(which zsh)"
  local current_shell
  current_shell="$(_zsh_current_shell)"
  if [[ "$current_shell" != *"zsh"* ]]; then
    molt_info "Setting zsh as default shell..."
    if ! chsh -s "$zsh_path"; then
      molt_error "zsh: chsh could not make $zsh_path the login shell"
      return 1
    fi
  fi

  # Verify Starship is installed
  if ! command -v starship &>/dev/null; then
    molt_error "Starship not found. Install it (https://starship.rs) then re-run."
    return 1
  fi

  # Link config from user repo
  local user_repo
  user_repo="$(molt_find_user_repo)" || return 1

  molt_link "$user_repo/config/zsh/zshrc" "$HOME/.zshrc" || return 1
  molt_link "$user_repo/config/zsh/zshenv" "$HOME/.zshenv" || return 1
  molt_link "$user_repo/config/zsh/zprofile" "$HOME/.zprofile" || return 1

  molt_install_config "config/starship/starship.toml" "$HOME/.config/starship.toml" || return 1

  # Generate iTerm2 SSH colors from instance config (cross-instance aggregation)
  _zsh_generate_iterm2_ssh_colors "$(_zsh_iterm2_ssh_colors_file)" || return 1

  molt_info "Liberator complete: zsh"
}

zsh_verify() {
  local errors=0

  if ! command -v zsh &>/dev/null; then
    molt_error "VERIFY FAIL: zsh not installed"
    errors=1
  fi

  if ! command -v starship &>/dev/null; then
    molt_error "VERIFY FAIL: Starship not installed"
    errors=1
  fi

  # _install links each of them; verifying only .zshrc let a broken .zshenv or
  # .zprofile pass verify after passing check. Same gap, one phase later.
  local zf
  for zf in .zshrc .zshenv .zprofile; do
    if ! molt_link_healthy "$HOME/$zf"; then
      molt_error "VERIFY FAIL: ~/${zf} $(molt_link_fault "$HOME/$zf")"
      errors=1
    fi
  done

  if [[ $errors -eq 0 ]]; then
    molt_info "Verified: zsh liberator is fully operational"
  fi
  return $errors
}
